//! Regenerates `backlog/examples/snapshot.ttl` from a live `gh api` call.
//!
//! Not exercised by the test suite (it needs real network access and repo
//! auth) -- see
//! [`docs/plans/BACKLOG_GITHUB_LOADER_PLAN.md`](../../../docs/plans/BACKLOG_GITHUB_LOADER_PLAN.md).
//! Run manually: `cargo run -p backlog --bin backlog-regenerate`.

use backlog::loader::add_generated_at;
use backlog::{GhCliSource, build_snapshot};
use dag_rdf::DEFAULT_GRAPH_ELEMENT_ID;
use std::path::Path;

fn main() {
    env_logger::init();
    let source = GhCliSource::new("daghovland", "rdf-datalog");
    let workspace_root = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("backlog/ has a parent")
        .to_path_buf();

    let mut ds = build_snapshot(&source, &workspace_root).unwrap_or_else(|e| {
        eprintln!("failed to build backlog snapshot: {e}");
        std::process::exit(1);
    });

    // Record when this run happened as a queryable triple (bl:generatedAt
    // on bl:CurrentSnapshot), not just the human-readable header comment
    // below -- a future dashboard (#378) needs to detect staleness via
    // SPARQL, which can't see a plain-text comment. See #380.
    let generated_at = chrono::Utc::now();
    add_generated_at(&mut ds, generated_at);

    let mut lines: Vec<String> = turtle::serialize_graph(&ds, DEFAULT_GRAPH_ELEMENT_ID)
        .lines()
        .map(str::to_string)
        .collect();
    // Sort so the checked-in snapshot doesn't reshuffle every run (quad
    // iteration order isn't a stability guarantee) -- see plan doc "Output
    // stability".
    lines.sort();

    let out_path = workspace_root.join("backlog/examples/snapshot.ttl");
    let header = format!(
        "# Generated by `cargo run -p backlog --bin backlog-regenerate`.\n\
         # DO NOT hand-edit -- see docs/plans/BACKLOG_GITHUB_LOADER_PLAN.md.\n\
         # Generated at: {}\n\n",
        generated_at.to_rfc3339()
    );
    std::fs::write(&out_path, format!("{header}{}\n", lines.join("\n")))
        .unwrap_or_else(|e| panic!("failed to write {}: {e}", out_path.display()));
    println!("wrote {} ({} lines)", out_path.display(), lines.len());
}
